package com.serenity.shared.logging;

import ch.qos.logback.classic.Level;
import ch.qos.logback.classic.LoggerContext;
import ch.qos.logback.classic.spi.LoggingEvent;
import java.sql.DriverManager;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

class AsyncDatabaseLogAppenderIntegrationTest {

    @Test
    void persistsBatchIncludingExceptionAndMdcFields() throws Exception {
        String url = "jdbc:h2:mem:app_logs;DB_CLOSE_DELAY=-1";
        try (var connection = DriverManager.getConnection(url, "sa", "")) {
            connection.createStatement().execute("CREATE TABLE app_logs ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TIMESTAMP WITH TIME ZONE NOT NULL, "
                    + "level VARCHAR(16), logger_name VARCHAR(512), thread_name VARCHAR(256), message CLOB, "
                    + "stack_trace CLOB, application_name VARCHAR(128), hostname VARCHAR(255), "
                    + "trace_id VARCHAR(128), user_id VARCHAR(128))");
        }

        LoggerContext context = new LoggerContext();
        AsyncDatabaseLogAppender appender = new AsyncDatabaseLogAppender();
        appender.setContext(context);
        appender.setJdbcUrl(url);
        appender.setUsername("sa");
        appender.setPassword("");
        appender.setBatchSize(10);
        appender.setFlushIntervalMs(10);
        appender.setMinimumLevel("WARN");
        appender.start();

        LoggingEvent event = new LoggingEvent();
        event.setLoggerName("com.serenity.integration.Sample");
        event.setLevel(Level.ERROR);
        event.setMessage("integration failure");
        event.setThreadName("integration-thread");
        event.setTimeStamp(System.currentTimeMillis());
        event.setMDCPropertyMap(java.util.Map.of("trace_id", "trace-123", "user_id", "42"));
        event.setThrowableProxy(new ch.qos.logback.classic.spi.ThrowableProxy(new IllegalStateException("broken")));

        appender.doAppend(event);
        TimeUnit.MILLISECONDS.sleep(100);
        appender.stop();
        context.stop();

        try (var connection = DriverManager.getConnection(url, "sa", "");
             var result = connection.createStatement().executeQuery("SELECT * FROM app_logs")) {
            org.junit.jupiter.api.Assertions.assertTrue(result.next());
            assertEquals("ERROR", result.getString("level"));
            assertEquals("integration failure", result.getString("message"));
            assertEquals("trace-123", result.getString("trace_id"));
            assertEquals("42", result.getString("user_id"));
            assertNotNull(result.getString("stack_trace"));
        }
    }
}
